// embed.mjs - write the contract suffixes from vectors/static.json into the ports as constants, so neither port
// re-parses the reference's ASM. Usage (repo root): node vectors/gen/embed.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const s = JSON.parse(readFileSync('vectors/static.json', 'utf8'))
const names = { MinSimple: 'MinSimple', AuthBolt: 'AuthBolt', SimpleMulti: 'SimpleMulti' }

let go = '// Code generated by vectors/gen/embed.mjs from vectors/static.json; DO NOT EDIT.\n\npackage b017\n\n'
for (const [k, n] of Object.entries(names)) {
  go += `// ${n}LockSuffixHex is the ${n} static lock suffix (sha256 ${s.suffixes[k].lockSha256}).\n`
  go += `const ${n}LockSuffixHex = "${s.suffixes[k].lockHex}"\n\n`
  go += `// ${n}UnlockSuffixHex is the ${n} unlock suffix (sha256 ${s.suffixes[k].unlockSha256}).\n`
  go += `const ${n}UnlockSuffixHex = "${s.suffixes[k].unlockHex}"\n\n`
}
writeFileSync('go/suffixes_gen.go', go)

let rs = '// Generated by vectors/gen/embed.mjs from vectors/static.json; do not edit.\n\n'
for (const [k, n] of Object.entries(names)) {
  const up = n.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase()
  rs += `/// ${n} static lock suffix (sha256 ${s.suffixes[k].lockSha256}).\n`
  rs += `pub const ${up}_LOCK_SUFFIX_HEX: &str = "${s.suffixes[k].lockHex}";\n\n`
  rs += `/// ${n} unlock suffix (sha256 ${s.suffixes[k].unlockSha256}).\n`
  rs += `pub const ${up}_UNLOCK_SUFFIX_HEX: &str = "${s.suffixes[k].unlockHex}";\n\n`
}
mkdirSync('rust/src', { recursive: true })
writeFileSync('rust/src/suffixes_gen.rs', rs)
console.log('wrote go/suffixes_gen.go and rust/src/suffixes_gen.rs')
